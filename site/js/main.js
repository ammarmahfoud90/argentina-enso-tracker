/* ── Utilities ── */
function d2y(str) {
  const d = new Date(str + 'T12:00:00Z');
  return d.getUTCFullYear() + d.getUTCMonth() / 12;
}
function oniY(v) {
  return C.yTop + (C.vTop - v) / (C.vTop - C.vBot) * (C.yBot - C.yTop);
}
function oniX(t, tMin, tMax) {
  return C.x0 + (t - tMin) / (tMax - tMin) * (C.x1 - C.x0);
}
function insetY(v) {
  return INSET.yTop + (INSET.vTop - v) / (INSET.vTop - INSET.vBot) * (INSET.yBot - INSET.yTop);
}
function insetX(t, tMin, tMax) {
  return INSET.x0 + (t - tMin) / (tMax - tMin) * (INSET.x1 - INSET.x0);
}
function rToOklch(r) {
  const a = Math.min(1, Math.abs(r) / 0.25);
  const ch = (r >= 0 ? 0.14 : 0.12) * a;
  const H = r >= 0 ? 30 : 262;
  const A = 0.12 + 0.55 * a;
  return `oklch(0.56 ${ch.toFixed(3)} ${H} / ${A.toFixed(2)})`;
}
function svgEl(tag, attrs, parent) {
  const e = document.createElementNS('http://www.w3.org/2000/svg', tag);
  for (const [k, v] of Object.entries(attrs)) e.setAttribute(k, String(v));
  if (parent) parent.appendChild(e);
  return e;
}
function svgText(parent, x, y, text, attrs = {}) {
  const e = svgEl('text', { x, y, ...attrs }, parent);
  e.textContent = text;
  return e;
}
