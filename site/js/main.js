function buildComparisonChart(divId, oniSeries, episodes, compareType) {
  const events = _notableEvents()[compareType] || [];
  const traces = [];
  const historicalColors = ['#A7AEBB', '#C7CCD6', '#D4D8DF', '#B8BDC7', '#DDE0E6'];

  /* Extract ONI values for a given start point, aligned to month 0 */
  function extractEpisode(startYear, startMonth, maxMonths) {
    const months = [];
    const values = [];
    for (const pt of oniSeries) {
      const d = new Date(pt.date + 'T12:00:00Z');
      const yr = d.getUTCFullYear();
      const mo = d.getUTCMonth() + 1;
      const offset = (yr - startYear) * 12 + (mo - startMonth);
      if (offset >= 0 && offset <= maxMonths) {
        months.push(offset);
        values.push(pt.oni);
      }
    }
    return { months, values };
  }

  /* Historical events */
  events.forEach((ev, i) => {
    const ep = extractEpisode(ev.startYear, ev.startMonth, 24);
    if (ep.months.length < 3) return;
    traces.push({
      x: ep.months, y: ep.values,
      type: 'scatter', mode: 'lines',
      line: { color: historicalColors[i % historicalColors.length], width: 1.5 },
      name: ev.label,
      hovertemplate: `<b>${ev.label}</b><br>Mes %{x}: ONI %{y:+.2f}<extra></extra>`,
    });
  });

  /* Current trajectory — scan backwards from end of ONI series to find
     the last ascending cross of the threshold, independent of confirmed episodes.
     This ensures we show the in-progress trajectory even if the formal
     5-season episode criterion hasn't been met yet. */
  const threshold = compareType === 'nino' ? 0.5 : -0.5;
  const meetsThreshold = compareType === 'nino'
    ? v => v >= threshold
    : v => v <= threshold;

  let crossIdx = -1;
  for (let i = oniSeries.length - 1; i > 0; i--) {
    if (!meetsThreshold(oniSeries[i].oni)) {
      /* Found the point where ONI drops below threshold — the trajectory
         starts at the next point (i+1) */
      crossIdx = i + 1;
      break;
    }
  }

  let currentStart = null;
  let currentLabel = t('label_current');
  if (crossIdx >= 0 && crossIdx < oniSeries.length) {
    const dStart = new Date(oniSeries[crossIdx].date + 'T12:00:00Z');
    const dEnd = new Date(oniSeries[oniSeries.length - 1].date + 'T12:00:00Z');
    currentStart = { year: dStart.getUTCFullYear(), month: dStart.getUTCMonth() + 1 };
    const endYear = dEnd.getUTCFullYear();
    currentLabel = dStart.getUTCFullYear() === endYear
      ? `Actual (${dStart.getUTCFullYear()})`
      : `Actual (${dStart.getUTCFullYear()}–${String(endYear).slice(-2)})`;
  }

  /* Fallback: use last 18 months if threshold never crossed */
  if (!currentStart) {
    const lastPt = oniSeries[oniSeries.length - 1];
    const d = new Date(lastPt.date + 'T12:00:00Z');
    currentStart = { year: d.getUTCFullYear() - 1, month: d.getUTCMonth() + 1 };
    currentLabel = `Actual (${currentStart.year}–${String(d.getUTCFullYear()).slice(-2)})`;
  }

  const current = extractEpisode(currentStart.year, currentStart.month, 24);
  const currentColor = compareType === 'nino' ? '#C2382A' : '#2A55D0';
  if (current.months.length > 0) {
    traces.push({
      x: current.months, y: current.values,
      type: 'scatter', mode: 'lines+markers',
      line: { color: currentColor, width: 3.5 },
      marker: { size: 7, color: currentColor, line: { color: '#FFFFFF', width: 1.5 } },
      name: currentLabel,
      hovertemplate: `<b>${currentLabel}</b><br>Mes %{x}: ONI %{y:+.2f}<extra></extra>`,
    });
  }

  /* Annotation on last point of current trajectory */
  const annotations = [];
  if (current.months.length > 0) {
    const lastIdx = current.months.length - 1;
    const lastOni = current.values[lastIdx];
    const lastMonth = current.months[lastIdx];
    annotations.push({
      x: lastMonth, y: lastOni,
      text: `${lastOni >= 0 ? '+' : ''}${lastOni.toFixed(2)}`,
      showarrow: true, arrowhead: 0, arrowcolor: currentColor,
      ax: 35, ay: -25,
      font: { family: 'IBM Plex Mono', size: 12, color: currentColor, weight: 700 },
      bgcolor: chartColors().annotBg, bordercolor: currentColor, borderwidth: 1, borderpad: 3,
    });
  }

  const cc = chartColors();
  const layout = {
    margin: { t: 10, r: 20, b: 50, l: 50 },
    xaxis: {
      title: { text: 'Meses desde inicio del episodio', font: { family: 'IBM Plex Mono', size: 12, color: cc.tick } },
      tickfont: { family: 'IBM Plex Mono', size: 11, color: cc.tick },
      gridcolor: cc.grid,
    },
    yaxis: {
      title: { text: 'ONI (°C)', font: { family: 'IBM Plex Mono', size: 12, color: cc.tick } },
      tickfont: { family: 'IBM Plex Mono', size: 11, color: cc.tick },
      gridcolor: cc.grid, zeroline: true, zerolinecolor: cc.zero,
    },
    shapes: [
      { type: 'line', xref: 'paper', yref: 'y', x0: 0, x1: 1, y0: 0.5, y1: 0.5,
        line: { color: '#C2382A', width: 1, dash: 'dot' } },
      { type: 'line', xref: 'paper', yref: 'y', x0: 0, x1: 1, y0: -0.5, y1: -0.5,
        line: { color: '#2A55D0', width: 1, dash: 'dot' } },
    ],
    annotations,
    legend: { font: { family: 'IBM Plex Mono', size: 11, color: cc.text }, x: 0, y: 1 },
    paper_bgcolor: cc.paper, plot_bgcolor: cc.plot,
    hovermode: 'closest',
    hoverlabel: { bgcolor: cc.hover, font: { family: 'IBM Plex Mono', size: 12, color: cc.hoverFont } },
  };

  const config = {
    responsive: true,
    displayModeBar: true,
    modeBarButtonsToRemove: ['lasso2d', 'select2d', 'autoScale2d'],
    displaylogo: false,
  };

  Plotly.newPlot(divId, traces, layout, config);

  /* Dynamic comparison note below chart */
  const noteId = divId + '-note';
  let noteEl = document.getElementById(noteId);
  if (!noteEl) {
    noteEl = document.createElement('p');
    noteEl.id = noteId;
    noteEl.style.cssText = 'margin:10px 0 0;font-size:12px;color:#555C68;font-family:IBM Plex Mono,monospace;line-height:1.55;max-width:76ch;';
    document.getElementById(divId).parentNode.insertBefore(noteEl, document.getElementById(divId).nextSibling);
  }

  if (current.months.length >= 2) {
    const N = current.months.length;
    const lastOni = current.values[N - 1];
    let noteText = `El episodio actual lleva ${N} meses desde el cruce de ${threshold >= 0 ? '+' : ''}${threshold.toFixed(1)}. La comparación gana valor a medida que avanza.`;

    /* Compare to historical events at same offset */
    const surpassed = [];
    for (const ev of events) {
      const ep = extractEpisode(ev.startYear, ev.startMonth, 24);
      const lastOffset = current.months[N - 1];
      const matchIdx = ep.months.indexOf(lastOffset);
      if (matchIdx >= 0 && ((compareType === 'nino' && lastOni > ep.values[matchIdx]) ||
                            (compareType !== 'nino' && lastOni < ep.values[matchIdx]))) {
        surpassed.push({ label: ev.label, val: ep.values[matchIdx] });
      }
    }
    if (surpassed.length > 0) {
      const names = surpassed.map(s => s.label).join(', ');
      noteText += ` A los ${N} meses del inicio, el ONI actual (${lastOni >= 0 ? '+' : ''}${lastOni.toFixed(2)}) supera al de ${names} en el mismo punto de su trayectoria.`;
    }
    noteEl.textContent = noteText;
  } else if (current.months.length === 1) {
    noteEl.textContent = `Episodio incipiente (1 mes). Demasiado temprano para comparaciones significativas.`;
  } else {
    noteEl.textContent = '';
  }
}

